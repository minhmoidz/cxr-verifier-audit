"""Generate the tables of the PRL supplementary material from runs on disk.

Outputs (outputs/generated/): supp_cells.tex (every attacker cell on the clean protocol),
supp_calibrated.tex (operating points with thresholds fixed on the calibration list),
supp_factorial.tex (all factorial cells), supp_exposure.tex (patient overlap between splits and
with the reference verifier's supplied training list). Run tools/prl_tables.py first.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import prl_tables as T  # noqa: E402

GEN = T.GEN
INIT = {"imagenet": "ImageNet", "vstar_clean": "Local", "chexgenbench": "MIMIC", "pretrained_ver": "Reference"}
ARCH = {"resnet50_bce": "released", "resnet50_monohead": "monotone head", "resnet50_adamw_headlr": "AdamW + head lr",
        "resnet50_metric_l1": "full", "convnext_tiny_bce": "ConvNeXt-T, released"}
SAN = {"none": "none", "ff_mu0.001": "field $\\mu{=}0.001$", "ff_mu0.005": "field $\\mu{=}0.005$",
       "ff_mu0.01": "field $\\mu{=}0.01$", "blur_s1.5": "blur $\\sigma{=}1.5$", "blur_s2": "blur $\\sigma{=}2$",
       "blur_s2.5": "blur $\\sigma{=}2.5$", "elastic_m0.035_keyed": "elastic 0.035", "elastic_m0.04_keyed": "elastic 0.04",
       "elastic_m0.045_keyed": "elastic 0.045", "privacy_net": "Privacy-Net", "dppix_b8_fixed": "DP-Pix $b{=}8$"}
HDR = "% GENERATED by tools/prl_supplement.py -- do not edit\n"


def pm(rows, k):
    m, s, n = T.stat(rows, k)
    return f"{m:.2f}$\\pm${s:.2f}"


def cells(runs):
    order_i = list(INIT); order_a = list(ARCH); order_s = list(SAN)
    keys = sorted(runs, key=lambda k: (order_i.index(k[0]), order_a.index(k[1]), -k[3], order_s.index(k[2])))
    L = [r"\begin{longtable}{lllrcccccc}", r"\toprule",
         r"Init. & Recipe & Sanitizer & lr & $n$ & AUC & TPR@1\% & Rank-1 & Ep. & Sel. ep.=1 \\", r"\midrule", r"\endhead"]
    for k in keys:
        rows = runs[k]; init, arch, san, lr = k
        ep = "/".join(str(r["sel_ep"]) for r in sorted(rows, key=lambda r: r["seed"]))
        L.append(f"{INIT[init]} & {ARCH[arch]} & {SAN[san]} & {lr:.0e} & {len(rows)} & {pm(rows, 'auc')} & "
                 f"{pm(rows, 'tpr1')} & {pm(rows, 'rank1')} & {ep} & {sum(r['sel_ep'] == 1 for r in rows)} \\\\")
    L += [r"\bottomrule", r"\end{longtable}"]
    open(os.path.join(GEN, "supp_cells.tex"), "w").write(HDR + "\n".join(L).replace("e-04", "e-4").replace("e-05", "e-5") + "\n")


def calibrated(runs):
    L = [r"\begin{tabular}{llccccc}", r"\toprule",
         r" & & & \multicolumn{2}{c}{Test-ROC} & \multicolumn{2}{c}{Calibration-list threshold} \\",
         r"\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
         r"Verifier & Sanitizer & Utility & FPR & TPR & realized FPR & TPR \\", r"\midrule"]
    import csv
    frozen = {r["sanitizer"]: float(r["test_macro_auc"]) for r in
              csv.DictReader(open(os.path.join(T.ROOT, "results", "e4", "e4_frozen_summary.csv")))}
    for att, init, arch in (("Reference", "pretrained_ver", "resnet50_bce"), ("ImageNet, full", "imagenet", "resnet50_metric_l1")):
        for san in ("none", "ff_mu0.001", "ff_mu0.005", "ff_mu0.01", "blur_s1.5", "blur_s2", "blur_s2.5",
                    "elastic_m0.035_keyed", "elastic_m0.04_keyed", "elastic_m0.045_keyed", "privacy_net", "dppix_b8_fixed"):
            rows = runs.get((init, arch, san, 1e-4), [])
            if rows:
                L.append(f"{att} & {SAN[san]} & {frozen.get(san, float('nan')):.2f} & 1.00 & {pm(rows, 'tpr1')} & "
                         f"{pm(rows, 'cal_fpr1')} & {pm(rows, 'cal_tpr1')} \\\\")
        L.append(r"\midrule")
    L[-1] = r"\bottomrule"; L.append(r"\end{tabular}")
    open(os.path.join(GEN, "supp_calibrated.tex"), "w").write(HDR + "\n".join(L) + "\n")


def factorial():
    d = json.load(open(os.path.join(T.ROOT, "artifacts", "factorial_results.json")))
    names = {"ff_mu0.01": "Learned field $\\mu{=}0.01$", "blur_s2": "Blur $\\sigma{=}2$", "elastic_m004": "Elastic 0.04"}
    cellk = [("SS", "SS", "sanitized_sanitized/sanitized_sanitized/orig"), ("SS", "SR", "sanitized_sanitized/sanitized_raw/orig"),
             ("SR", "SS", "sanitized_raw/sanitized_sanitized/orig"), ("SR", "SR", "sanitized_raw/sanitized_raw/orig"),
             ("SS", "SS, disjoint", "sanitized_sanitized/sanitized_sanitized/disjoint"),
             ("SR", "SR, disjoint", "sanitized_raw/sanitized_raw/disjoint")]
    def f(e, bold=False):
        pt = f"{e['point']:.2f}"
        return T.neg((f"\\textbf{{{pt}}}" if bold else pt) + f" [{e['ci'][0]:.2f}, {e['ci'][1]:.2f}]")
    L = [r"\begin{tabular}{lllcc}", r"\toprule", r"Sanitizer ($n$ seeds) & Train & Validation & AUC & TPR@1\% \\", r"\midrule"]
    for cfg, v in d["results"].items():
        # Bold: highest point estimate among the four main pairing cells, per sanitizer and metric.
        best = {m: max((k for _, _, k in cellk[:4]), key=lambda k: v[m][k]["point"]) for m in ("auc", "tpr")}
        for i, (tp, vp, k) in enumerate(cellk):
            lab = f"{names[cfg]} ({v['n_seeds']})" if i == 0 else ""
            L.append(f"{lab} & {tp} & {vp} & {f(v['auc'][k], k == best['auc'])} & {f(v['tpr'][k], k == best['tpr'])} \\\\")
        for nm, k in (("train effect", "train_effect"), ("validation effect", "val_effect"), ("interaction", "interaction")):
            L.append(f" & \\multicolumn{{2}}{{l}}{{{nm}}} & {f(v['auc'][k])} & {f(v['tpr'][k])} \\\\")
        L.append(r"\midrule")
    L[-1] = r"\bottomrule"; L.append(r"\end{tabular}")
    open(os.path.join(GEN, "supp_factorial.tex"), "w").write(HDR + "\n".join(L) + "\n")


def exposure():
    pid = lambda f: f.split("_")[0]
    def pts(path):
        return {pid(x) for l in open(path) for x in l.split()[:2]}
    ref = {pid(l.split()[0]) for l in open(os.path.join(T.ROOT, "image_pairs", "train_val_list.txt"))}
    S = [("Verifier training", "results/clean_splits/d_att_train_clean.txt"),
         ("Local-verifier pretraining", "results/clean_splits/d_pretrain_clean.txt"),
         ("Validation (released)", "image_pairs/image_pairs_validation_2000.txt"),
         ("Calibration (disjoint)", "image_pairs/image_pairs_validation_disjoint_700.txt"),
         ("Test (released)", "image_pairs/image_pairs_testing_5000.txt"),
         ("Factorial training (released)", "image_pairs/image_pairs_training_10000.txt")]
    P = {n: pts(os.path.join(T.ROOT, p)) for n, p in S}
    names = [n for n, _ in S]
    L = [r"\begin{tabular}{l r " + "r" * len(names) + " r}", r"\toprule",
         "Split & Patients & " + " & ".join(f"({i + 1})" for i in range(len(names))) + r" & In ref.\ list \\", r"\midrule"]
    for i, a in enumerate(names):
        row = [f"({i + 1}) {a}", f"{len(P[a]):,}"]
        for b in names:
            row.append("--" if a == b else f"{len(P[a] & P[b]):,}")
        row.append(f"{len(P[a] & ref):,}")
        L.append(" & ".join(row) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    open(os.path.join(GEN, "supp_exposure.tex"), "w").write(HDR + "\n".join(L).replace(",", "{,}") + "\n")
    return len(ref)


def paired():
    P = json.load(open(os.path.join(T.ROOT, "results", "prl_final", "paired_ci.json")))
    nm = {"blur_s2": "Gaussian blur $\\sigma{=}2$", "elastic_m0.045_keyed": "Elastic 0.045"}
    ci = lambda c: T.neg(f"[{c[0]:.2f}, {c[1]:.2f}]")
    side = lambda c: c[0] > 0 or c[1] < 0

    def f(v, cis=()):
        """Bold an estimate when both of its intervals lie on the same side of zero."""
        txt = T.neg(f"{v:.2f}")
        ok = len(cis) == 2 and all(side(c) for c in cis) and (cis[0][0] > 0) == (cis[1][0] > 0)
        return f"\\textbf{{{txt}}}" if ok else txt
    L = [r"\begin{tabular}{llccc}", r"\toprule",
         r"Comparison (field $-$ control) & Quantity & Point & 95\% CI, patients & 95\% CI, patients + seeds \\", r"\midrule"]
    for ctrl in P["controls"]:
        lk = P["leakage"][ctrl]; u = P["utility_frozen"][ctrl]
        for q, lab in (("tpr1", "TPR@1\\% (points)"), ("auc", "AUC (points)")):
            e = lk[q]
            L.append(f"{nm[ctrl] if q == 'tpr1' else ''} & {lab} & {f(e['point'], (e['patient_ci'], e['hier_ci']))} & "
                     f"{ci(e['patient_ci'])} & {ci(e['hier_ci'])} \\\\")
        L.append(f" & frozen macro AUC (points) & {f(u['point'])} & {ci(u['patient_ci'])} & -- \\\\")
        L.append(r"\midrule")
    L[-1] = r"\bottomrule"; L.append(r"\end{tabular}")
    open(os.path.join(GEN, "supp_paired.tex"), "w").write(HDR + "\n".join(L) + "\n")


def rho_sensitivity(runs):
    specs = [c for c in T.CONSTRUCTIONS if c is not None]
    raw = {c[0]: T.stat(runs[(c[1], c[2], "none", c[3])], "tpr1")[0] for c in specs}
    best = max(raw.values()); best9 = max(v for k, v in raw.items() if not k.startswith("Reference"))
    L = [r"\begin{tabular}{lcccc}", r"\toprule",
         r"Configuration & raw TPR@1\% & $\rho$ (all 10) & $\rho$ (reference removed) \\", r"\midrule"]
    # Bold: largest score in each column among eligible configurations.
    b = lambda x, top: f"\\textbf{{{x:.2f}}}" if abs(x - top) < 1e-12 else f"{x:.2f}"
    for k, v in raw.items():
        r9 = "--" if k.startswith("Reference") else b(v / best9, 1.0)
        L.append(f"{k} & {b(v, best)} & {b(v / best, 1.0)} & {r9} \\\\")
    L += [r"\midrule",
          f"Pass at 0.50 & & {sum(v / best >= 0.5 for v in raw.values())}/10 & "
          f"{sum(v / best9 >= 0.5 for k, v in raw.items() if not k.startswith('Reference'))}/9 \\\\",
          f"Pass at 0.45 & & {sum(v / best >= 0.45 for v in raw.values())}/10 & "
          f"{sum(v / best9 >= 0.45 for k, v in raw.items() if not k.startswith('Reference'))}/9 \\\\",
          r"\bottomrule", r"\end{tabular}"]
    open(os.path.join(GEN, "supp_rho.tex"), "w").write(HDR + "\n".join(L) + "\n")


def main():
    runs = T.load_runs()
    cells(runs); calibrated(runs); factorial(); n_ref = exposure(); paired(); rho_sensitivity(runs)
    print(f"wrote supplementary tables to {GEN} (reference list: {n_ref} patients)")


if __name__ == "__main__":
    main()
