"""Analysis of the locked factorial design (DEC-2026-11-02-001).

Reads per-seed test predictions for every cell, computes AUC and test-ROC TPR@1%FPR, and
paired hierarchical bootstrap (patient dyadic weights x seed resampling, same draw for every
cell in a contrast) for:
  train effect   = mean over val pairing of (SR-train - SS-train)     [orig val list]
  val effect     = mean over train pairing of (SR-val - SS-val)       [orig val list]
  interaction    = (SR,SR - SR,SS) - (SS,SR - SS,SS)
  disjoint effect = disjoint-val minus orig-val, for train=val in {SS, SR}
Writes artifacts/factorial_results.json and outputs/generated/factorial_tables.tex.
Seeds are paired by index. Usage: python3 tools/analyze_factorial.py [--n_boot 2000]
       python3 tools/analyze_factorial.py --tables-only   (rewrite the tables from the JSON)
"""
import argparse, json, os, sys
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "artifacts/paper_upgrade/phase5_pairing_audit"))
sys.path.insert(0, os.path.join(ROOT, "artifacts/paper_upgrade/phase1_patient_bootstrap"))
import pairing_resolver as R  # noqa: E402
import phase1_bootstrap as B  # noqa: E402

SS, SR = "sanitized_sanitized", "sanitized_raw"
CFGS = {"ff_mu0.01": ("Learned $\\mu{=}0.01$", 5), "blur_s2": ("Blur $\\sigma{=}2$", 3),
        "elastic_m004": ("Elastic $\\mu{=}0.04$", 3)}


def load(cfg, tp, vp, vl, seed):
    i = R.cell_id(cfg, "pretrained_ver", tp, seed, vp, vl)
    return np.loadtxt(os.path.join(ROOT, "archive", i, f"{i}_labels_predictions.txt"), skiprows=1)[:, 1]


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--n_boot", type=int, default=2000)
    ap.add_argument("--tables-only", action="store_true",
                    help="skip the bootstrap and rewrite the tables from artifacts/factorial_results.json")
    args = ap.parse_args(); n_boot = args.n_boot
    if args.tables_only:
        write_tables(json.load(open(os.path.join(ROOT, "artifacts/factorial_results.json")))["results"])
        return
    _, _, y, pa, pb = B.load_pairs(B.TEST_PAIRS)
    ca, cb, is_pos, npat = B._encode_pids(pa, pb)
    out = {}
    for cfg, (_, nseed) in CFGS.items():
        S = {}
        for tp in (SS, SR):
            for vp in (SS, SR):
                S[(tp, vp, "orig")] = np.stack([load(cfg, tp, vp, "orig", s) for s in range(nseed)])
            S[(tp, tp, "disjoint")] = np.stack([load(cfg, tp, tp, "disjoint", s) for s in range(nseed)])
        def metric(sc, w, kind):
            v = [B.weighted_auc(y, s, w) if kind == "auc" else B.weighted_tpr_at(y, s, w)[0] for s in sc]
            return 100 * np.array(v)
        def contrasts(idx, w, kind):
            m = {k: metric(S[k][idx], w, kind).mean() for k in S}
            return {
                **{"/".join(k): v for k, v in m.items()},
                "train_effect": np.mean([m[(SR, vp, "orig")] - m[(SS, vp, "orig")] for vp in (SS, SR)]),
                "val_effect": np.mean([m[(tp, SR, "orig")] - m[(tp, SS, "orig")] for tp in (SS, SR)]),
                "interaction": (m[(SR, SR, "orig")] - m[(SR, SS, "orig")]) - (m[(SS, SR, "orig")] - m[(SS, SS, "orig")]),
                "disjoint_minus_orig_SS": m[(SS, SS, "disjoint")] - m[(SS, SS, "orig")],
                "disjoint_minus_orig_SR": m[(SR, SR, "disjoint")] - m[(SR, SR, "orig")],
            }
        res = {}
        for kind in ("auc", "tpr"):
            rng = np.random.default_rng(20261109)
            point = contrasts(np.arange(nseed), np.ones(len(y)), kind)
            reps = []
            for _ in range(n_boot):
                w = B.dyadic_weights_fast(ca, cb, is_pos, npat, rng)
                idx = rng.integers(0, nseed, nseed)
                reps.append(contrasts(idx, w, kind))
            res[kind] = {k: {"point": float(point[k]),
                             "ci": [float(np.percentile([r[k] for r in reps], 2.5)),
                                    float(np.percentile([r[k] for r in reps], 97.5))]} for k in point}
        out[cfg] = {"n_seeds": nseed, **res}
    os.makedirs(os.path.join(ROOT, "artifacts"), exist_ok=True)
    json.dump({"n_boot": n_boot, "rng_seed": 20261109, "results": out},
              open(os.path.join(ROOT, "artifacts/factorial_results.json"), "w"), indent=1)
    write_tables(out)


def write_tables(out):
    f = lambda d: f"{d['point']:.2f} [{d['ci'][0]:.2f}, {d['ci'][1]:.2f}]"
    L = ["% GENERATED by tools/analyze_factorial.py -- do not edit",
         "\\begin{tabular}{llrr}\\toprule", "Sanitizer & Train / val pairing & AUC & TPR@1\\%FPR \\\\\\midrule"]
    for cfg, (name, ns) in CFGS.items():
        for tp, vp in ((SS, SS), (SS, SR), (SR, SS), (SR, SR)):
            k = f"{tp}/{vp}/orig"
            T = lambda x: {"sanitized_sanitized": "SS", "sanitized_raw": "SR"}[x]
            L.append(f"{name if (tp, vp) == (SS, SS) else ''} ({ns} seeds) & {T(tp)} / {T(vp)} & "
                     f"{out[cfg]['auc'][k]['point']:.2f} & {out[cfg]['tpr'][k]['point']:.2f} \\\\" if (tp, vp) == (SS, SS)
                     else f" & {T(tp)} / {T(vp)} & {out[cfg]['auc'][k]['point']:.2f} & {out[cfg]['tpr'][k]['point']:.2f} \\\\")
        L.append("\\midrule")
    L[-1] = "\\bottomrule\\end{tabular}"
    L += ["", "% effects", "\\begin{tabular}{lrrr}\\toprule", "Sanitizer & Train effect & Val effect & Interaction \\\\\\midrule"]
    for cfg, (name, _) in CFGS.items():
        a = out[cfg]["auc"]
        L.append(f"{name} & {f(a['train_effect'])} & {f(a['val_effect'])} & {f(a['interaction'])} \\\\")
    L += ["\\bottomrule\\end{tabular}", "", "% disjoint validation", "\\begin{tabular}{lrr}\\toprule",
          "Sanitizer & $\\Delta$AUC (SS/SS) & $\\Delta$AUC (SR/SR) \\\\\\midrule"]
    for cfg, (name, _) in CFGS.items():
        a = out[cfg]["auc"]
        L.append(f"{name} & {f(a['disjoint_minus_orig_SS'])} & {f(a['disjoint_minus_orig_SR'])} \\\\")
    L.append("\\bottomrule\\end{tabular}")
    os.makedirs(os.path.join(ROOT, "outputs", "generated"), exist_ok=True)
    open(os.path.join(ROOT, "outputs", "generated", "factorial_tables.tex"), "w").write("\n".join(L) + "\n")
    for cfg in out:
        print(cfg, {k: f(v) for k, v in out[cfg]["auc"].items() if k in ("train_effect", "val_effect", "interaction", "disjoint_minus_orig_SS", "disjoint_minus_orig_SR")})
        print("  TPR", {k: f(v) for k, v in out[cfg]["tpr"].items() if k in ("train_effect", "val_effect")})


if __name__ == "__main__":
    main()
