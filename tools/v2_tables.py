def part_t4():
    p = R("T4", "recipe_mechanism.json")
    if not os.path.isfile(p):
        print("T4: missing", p); return
    d = json.load(open(p))
    G = d["head_groups"]
    for g, stem in (("imagenet_released/", "t4-inrel"), ("e3_imagenet_released/", "t4-e3"),
                    ("reference_verifier", "t4-ref"), ("untrained_default_init/", "t4-init")):
        e = G[g]
        put(stem + "-n", e["n"])
        for m, k in (("frac_negative", "fneg"), ("sum_positive", "spos"), ("sum_negative", "sneg"), ("bias", "bias")):
            put(f"{stem}-{k}-lo", e[f"{m}_range"][0]); put(f"{stem}-{k}-hi", e[f"{m}_range"][1])
    rows = [v for k, v in d["heads"].items() if k.startswith(("imagenet_released/", "e3_imagenet_released/"))]
    put("t4-all-n", len(rows))
    put("t4-all-pneg-lo", 100 * min(r["frac_negative"] for r in rows))
    put("t4-all-pneg-hi", 100 * max(r["frac_negative"] for r in rows))
    for m, k in (("sum_positive", "spos"), ("sum_negative", "sneg")):
        put(f"t4-all-{k}-lo", min(r[m] for r in rows)); put(f"t4-all-{k}-hi", max(r[m] for r in rows))
    ini = [v for k, v in d["heads"].items() if k.startswith("untrained_default_init/")]
    put("t4-init-pneg-lo", 100 * min(r["frac_negative"] for r in ini))
    put("t4-init-pneg-hi", 100 * max(r["frac_negative"] for r in ini))
    put("t4-ref-pneg", 100 * G["reference_verifier"]["frac_negative_range"][0])
    S = d["dynamics_summary"]
    L = [r"\begin{tabular}{llcccc}", r"\toprule",
         r"Recipe (ImageNet init.) & Images & Selected epochs & Val.\ loss, epoch 1 & Min.\ val.\ loss & Test AUC \\",
         r"\midrule"]
    for rec in ("released", "head change", "optimizer change", "full recipe"):
        for san, lab in (("none", "raw"), ("ff_mu0.01", "$\\mu{=}0.01$")):
            e = S[f"{rec}/{san}"]
            put(f"t4-{rec.replace(' ', '')}-{san.replace('_', '').replace('.', '')}-vl1", e["val_loss_ep1_mean"])
            put(f"t4-{rec.replace(' ', '')}-{san.replace('_', '').replace('.', '')}-vlmin", e["val_loss_min_mean"])
            L.append(f"{rec.capitalize() if san == 'none' else ''} & {lab} & {', '.join(map(str, e['selected_epoch']))} & "
                     f"{e['val_loss_ep1_mean']:.3f} & {e['val_loss_min_mean']:.3f} & {e['test_auc_mean']:.2f} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write("supp_v2_recipe_dyn.tex", L)
    L = [r"\begin{tabular}{lccccc}", r"\toprule",
         r"Head & $n$ & Negative weights (fraction) & $\sum w_+$ & $\sum w_-$ & Bias \\", r"\midrule"]
    for g, lab in (("untrained_default_init/", "Untrained (default initialization)"),
                   ("imagenet_released/", "ImageNet init., released recipe (this study)"),
                   ("e3_imagenet_released/", "ImageNet init., released protocol (E3)"),
                   ("reference_verifier", "Reference verifier (released weights)")):
        e = G[g]
        rng = lambda m, dd=2: NEG(f"{e[m + '_range'][0]:.{dd}f}") + (
            "" if e["n"] == 1 else "--" + NEG(f"{e[m + '_range'][1]:.{dd}f}"))
        L.append(f"{lab} & {e['n']} & {rng('frac_negative')} & {rng('sum_positive', 1)} & {rng('sum_negative', 1)} & "
                 f"{rng('bias')} \\\\")
