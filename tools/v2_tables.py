            nseeds.add(len(cn["seeds"]))
            for pr in ("SR", "SS"):
                ca = dc["arms"][f"v3c_{ver}/{san}/{pr}"]
                nseeds.add(len(ca["seeds"]))
                for m in ("auc", "tpr1"):
                    put(f"v3c-nih-{V[ver]}-{SC[san]}-{pr.lower()}-{m}", cn[f"ext/{pr}/{m}"]["point"])
                    put(f"v3c-cx-{V[ver]}-{SC[san]}-{pr.lower()}-{m}", ca[m])
