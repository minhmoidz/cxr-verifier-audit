def part_anchor():
    """Within-study anchors for published values: the 10-seed released-code reproduction (results/E3/
    released_code_10seed) and the zero-shot released reference verifier on raw test pairs (E1E2 scorer)."""
    from sklearn.metrics import roc_auc_score
    d = R("E3", "released_code_10seed")
    if not os.path.isdir(d):
        print("anchor: missing", d); return
    for tag, stem in (("none", "rc-raw"), ("ff_mu0.01", "rc-ff"), ("ff_mu0.005", "rc-ff005"), ("ff_mu0.001", "rc-ff001")):
        a = []
        for s in range(10):
            f = os.path.join(d, f"ver_{tag}_seed{s}", f"ver_{tag}_seed{s}_labels_predictions.txt")
            x = np.loadtxt(f, skiprows=1)
            a.append(100 * roc_auc_score(x[:, 0], x[:, 1]))
        put(f"{stem}-auc", float(np.mean(a))); put(f"{stem}-auc-sd", float(np.std(a, ddof=1))); put(f"{stem}-n", len(a))
    z = R("E1E2", "scores", "zeroshot__reference__none__s0.npz")
    if os.path.isfile(z):
        x = np.load(z)
        put("zs-ref-raw-auc", float(100 * roc_auc_score(x["test_y"], x["test_SR_logit"])))
    print("anchor: ok")


