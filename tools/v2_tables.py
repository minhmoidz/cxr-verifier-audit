def cfg_code(cfg):
    p = cfg.split("/")
    return "-".join([FAM[p[0]], SAN[p[1]]] + ([p[2].lower()] if len(p) > 2 else []))


def ent_txt(e, d=2, mode="patient+seed"):
    return NEG(f"{e['point']:.{d}f}") + " " + ci_txt(e[mode], d)


