"""Generate every number and table added in revision round v2 from results/ (never typed by hand).

Reads (each part is skipped with a message if its input is missing; the manuscript then prints a red
TODO for the missing macros, which the build check catches):
  results/E4/secondary_ci.json        E4, T2   (tools/v2_secondary_ci.py)
  results/T4/recipe_mechanism.json    T4       (tools/v2_recipe_mechanism.py)
  results/E1E2/extended_ci.json       E1, E2   (tools/v2_extended_ci.py)
  results/E1E2/scores/*.json          replicate consistency of retrained checkpoints
  results/E3/e3_ci.json               E3       (tools/v2_e3_ci.py)
  results/E5/...                      E5       (scripts/run_e5.py)
Writes outputs/generated/numbers_v2.tex (read with \\val{key}, \\val{key@1}, \\val{key@0} like
numbers.tex), the supplementary tables supp_v2_*.tex, and frontier_e5.csv for the figure.
Usage: python3 tools/v2_tables.py
"""
import csv
import glob
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import prl_tables as T  # noqa: E402

GEN = os.path.join(ROOT, "outputs", "generated")
R = lambda *p: os.path.join(ROOT, "results", *p)
HDR = "% GENERATED by tools/v2_tables.py -- do not edit\n"
N = {}          # key -> float or int
NEG = T.neg


def put(key, v):
    assert key not in N, f"duplicate macro {key}"
    N[key] = v


def ci_txt(c, d=2):
    return NEG(f"[{c[0]:.{d}f}, {c[1]:.{d}f}]")


def bold_if_excludes_zero(pt, cis, d=2):
    txt = NEG(f"{pt:.{d}f}")
    ok = all(c[0] > 0 or c[1] < 0 for c in cis) and len({c[0] > 0 for c in cis}) == 1
    return f"\\textbf{{{txt}}}" if ok else txt


def write(name, lines):
    open(os.path.join(GEN, name), "w").write(HDR + "\n".join(lines) + "\n")


# ----------------------------------------------------------------------------- E4 / T2
E4_KEYS = {  # quantity in secondary_ci.json -> macro stem
    "imagenet_full/field_minus_b2/tpr1": "e4-in-fb2-tpr", "imagenet_full/field_minus_b2/auc": "e4-in-fb2-auc",
    "imagenet_full/field_minus_e04/tpr1": "e4-in-fe04-tpr", "imagenet_full/field_minus_e04/auc": "e4-in-fe04-auc",
    "reference/field_minus_e04/tpr1": "e4-ref-fe04-tpr", "reference/field_minus_e04/auc": "e4-ref-fe04-auc",
    "reference/field_minus_b2/tpr1": "e4-ref-fb2-tpr", "reference/field_minus_b2/auc": "e4-ref-fb2-auc",
    "reference/field_minus_e045/tpr1": "e4-ref-fe045-tpr", "reference/field_minus_e045/auc": "e4-ref-fe045-auc",
    "reference/field_over_b2/tpr1": "t2-ref-fob2", "imagenet_full/field_over_b2/tpr1": "t2-in-fob2",
    "reference/field_over_raw/tpr1": "t2-ref-for", "imagenet_full/field_over_raw/tpr1": "t2-in-for",
    "reference/b2_over_raw/tpr1": "t2-ref-b2or", "imagenet_full/b2_over_raw/tpr1": "t2-in-b2or",
    "reference/e04_over_raw/tpr1": "t2-ref-e04or", "imagenet_full/e04_over_raw/tpr1": "t2-in-e04or",
    "reference/field_over_e04/tpr1": "t2-ref-foe04", "imagenet_full/field_over_e04/tpr1": "t2-in-foe04",
    "reference/field_minus_b2_over_raw/tpr1": "t2-ref-nm", "imagenet_full/field_minus_b2_over_raw/tpr1": "t2-in-nm",
    "between/field_over_b2/tpr1": "t2-btw-fob2", "between/field_minus_b2/tpr1": "t2-btw-fb2",
    "between/field_minus_b2_over_raw/tpr1": "t2-btw-nm",
}


def part_e4():
    p = R("E4", "secondary_ci.json")
    if not os.path.isfile(p):
        print("E4: missing", p); return
    d = json.load(open(p))
    Q = d["quantities"]
    for q, stem in E4_KEYS.items():
        e = Q[q]
        put(stem, e["point"])
        put(stem + "-plo", e["patient"][0]); put(stem + "-phi", e["patient"][1])
        put(stem + "-hlo", e["patient+seed"][0]); put(stem + "-hhi", e["patient+seed"][1])
    put("e4-nboot", d["n_boot"])
    # Table: contrasts (field minus control) for both verifiers, TPR@1% and AUC.
    rows = [("ImageNet verifier, full recipe", "Gaussian blur $\\sigma{=}2$", "imagenet_full/field_minus_b2"),
            ("", "Elastic 0.04", "imagenet_full/field_minus_e04"),
            ("Reference verifier", "Gaussian blur $\\sigma{=}2$", "reference/field_minus_b2"),
            ("", "Elastic 0.04", "reference/field_minus_e04"),
            ("", "Elastic 0.045", "reference/field_minus_e045")]
    L = [r"\begin{tabular}{llllll}", r"\toprule",
         r"Verifier & Control & Quantity & Point & 95\% CI, patients & 95\% CI, patients + seeds \\", r"\midrule"]
    for i, (ver, ctrl, q) in enumerate(rows):
        if i == 2:
            L.append(r"\midrule")
        for j, (m, lab) in enumerate((("tpr1", "TPR@1\\% (points)"), ("auc", "AUC (points)"))):
            e = Q[f"{q}/{m}"]
            L.append(f"{ver if j == 0 else ''} & {ctrl if j == 0 else ''} & {lab} & "
                     f"{bold_if_excludes_zero(e['point'], (e['patient'], e['patient+seed']))} & "
                     f"{ci_txt(e['patient'])} & {ci_txt(e['patient+seed'])} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write("supp_v2_e4.tex", L)
    # Table: relative measures (T2).
    rows = [("TPR(field) / TPR(raw)", "field_over_raw"), ("TPR(blur) / TPR(raw)", "b2_over_raw"),
            ("TPR(elastic 0.04) / TPR(raw)", "e04_over_raw"), ("TPR(field) / TPR(blur)", "field_over_b2"),
            ("TPR(field) / TPR(elastic 0.04)", "field_over_e04"),
            ("[TPR(field) $-$ TPR(blur)] / TPR(raw)", "field_minus_b2_over_raw")]
    L = [r"\begin{tabular}{lccc}", r"\toprule",
         r"Measure & Reference verifier & ImageNet verifier, full recipe & Difference (reference $-$ ImageNet) \\",
         r"\midrule"]
    for lab, q in rows:
        a, b = Q[f"reference/{q}/tpr1"], Q[f"imagenet_full/{q}/tpr1"]
        btw = Q.get(f"between/{q}/tpr1")
        fmt = lambda e: NEG(f"{e['point']:.2f}") + " " + ci_txt(e["patient+seed"])
        L.append(f"{lab} & {fmt(a)} & {fmt(b)} & {fmt(btw) if btw else '--'} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write("supp_v2_ratio.tex", L)
    print("E4: ok")


# ----------------------------------------------------------------------------- T4
def part_t4():
    p = R("T4", "recipe_mechanism.json")
    if not os.path.isfile(p):
        print("T4: missing", p); return
    d = json.load(open(p))
    G = d["head_groups"]
    for g, stem in (("imagenet_released/", "t4-inrel"), ("e3_imagenet_released/", "t4-e3"),
                    ("reference_verifier", "t4-ref"), ("untrained_default_init/", "t4-init")):
        e = G[g]
        put(stem + "-n", e["n"])
        for m, k in (("frac_negative", "fneg"), ("sum_positive", "spos"), ("sum_negative", "sneg"), ("bias", "bias")):
            put(f"{stem}-{k}-lo", e[f"{m}_range"][0]); put(f"{stem}-{k}-hi", e[f"{m}_range"][1])
    rows = [v for k, v in d["heads"].items() if k.startswith(("imagenet_released/", "e3_imagenet_released/"))]
    put("t4-all-n", len(rows))
    put("t4-all-pneg-lo", 100 * min(r["frac_negative"] for r in rows))
    put("t4-all-pneg-hi", 100 * max(r["frac_negative"] for r in rows))
    for m, k in (("sum_positive", "spos"), ("sum_negative", "sneg")):
        put(f"t4-all-{k}-lo", min(r[m] for r in rows)); put(f"t4-all-{k}-hi", max(r[m] for r in rows))
    ini = [v for k, v in d["heads"].items() if k.startswith("untrained_default_init/")]
    put("t4-init-pneg-lo", 100 * min(r["frac_negative"] for r in ini))
    put("t4-init-pneg-hi", 100 * max(r["frac_negative"] for r in ini))
    put("t4-ref-pneg", 100 * G["reference_verifier"]["frac_negative_range"][0])
    S = d["dynamics_summary"]
    L = [r"\begin{tabular}{llcccc}", r"\toprule",
         r"Recipe (ImageNet init.) & Images & Selected epochs & Val.\ loss, epoch 1 & Min.\ val.\ loss & Test AUC \\",
         r"\midrule"]
    for rec in ("released", "head change", "optimizer change", "full recipe"):
        for san, lab in (("none", "raw"), ("ff_mu0.01", "$\\mu{=}0.01$")):
            e = S[f"{rec}/{san}"]
            put(f"t4-{rec.replace(' ', '')}-{san.replace('_', '').replace('.', '')}-vl1", e["val_loss_ep1_mean"])
            put(f"t4-{rec.replace(' ', '')}-{san.replace('_', '').replace('.', '')}-vlmin", e["val_loss_min_mean"])
            L.append(f"{rec.capitalize() if san == 'none' else ''} & {lab} & {', '.join(map(str, e['selected_epoch']))} & "
                     f"{e['val_loss_ep1_mean']:.3f} & {e['val_loss_min_mean']:.3f} & {e['test_auc_mean']:.2f} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write("supp_v2_recipe_dyn.tex", L)
    L = [r"\begin{tabular}{lccccc}", r"\toprule",
         r"Head & $n$ & Negative weights (fraction) & $\sum w_+$ & $\sum w_-$ & Bias \\", r"\midrule"]
    for g, lab in (("untrained_default_init/", "Untrained (default initialization)"),
                   ("imagenet_released/", "ImageNet init., released recipe (this study)"),
                   ("e3_imagenet_released/", "ImageNet init., released protocol (E3)"),
                   ("reference_verifier", "Reference verifier (released weights)")):
        e = G[g]
        rng = lambda m, dd=2: NEG(f"{e[m + '_range'][0]:.{dd}f}") + (
            "" if e["n"] == 1 else "--" + NEG(f"{e[m + '_range'][1]:.{dd}f}"))
        L.append(f"{lab} & {e['n']} & {rng('frac_negative')} & {rng('sum_positive', 1)} & {rng('sum_negative', 1)} & "
                 f"{rng('bias')} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write("supp_v2_recipe_head.tex", L)
    print("T4: ok")


# ----------------------------------------------------------------------------- T3 anchors
def part_anchor():
    """Within-study anchors for published values: the 10-seed released-code reproduction (results/E3/
    released_code_10seed) and the zero-shot released reference verifier on raw test pairs (E1E2 scorer)."""
    from sklearn.metrics import roc_auc_score
    d = R("E3", "released_code_10seed")
    if not os.path.isdir(d):
        print("anchor: missing", d); return
    for tag, stem in (("none", "rc-raw"), ("ff_mu0.01", "rc-ff"), ("ff_mu0.005", "rc-ff005"), ("ff_mu0.001", "rc-ff001")):
        a = []
        for s in range(10):
            f = os.path.join(d, f"ver_{tag}_seed{s}", f"ver_{tag}_seed{s}_labels_predictions.txt")
            x = np.loadtxt(f, skiprows=1)
            a.append(100 * roc_auc_score(x[:, 0], x[:, 1]))
        put(f"{stem}-auc", float(np.mean(a))); put(f"{stem}-auc-sd", float(np.std(a, ddof=1))); put(f"{stem}-n", len(a))
    z = R("E1E2", "scores", "zeroshot__reference__none__s0.npz")
    if os.path.isfile(z):
        x = np.load(z)
        put("zs-ref-raw-auc", float(100 * roc_auc_score(x["test_y"], x["test_SR_logit"])))
    print("anchor: ok")


