    num = lambda x: float(x.split("$")[0])
    rows = [[x.strip() for x in l.rstrip("\\ ").split("&")] if "&" in l else l for l in body]
    for r in rows:
        if isinstance(r, list):
            assert len(r) == 8, r
            del r[3]
    best = {j: max(num(r[j]) for r in rows if isinstance(r, list)) for j in range(1, 6)}
