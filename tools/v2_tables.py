    first = True
    for fam in ("reference", "imagenet_full", "e5"):
        rows = [s for s in SAN if f"{fam}/{s}" in C]
        if not rows:
            continue
        if not first:
            L.append(r"\midrule")
        first = False
        for i, s in enumerate(rows):
            e = C[f"{fam}/{s}"]
