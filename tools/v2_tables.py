def write_numbers():
    ints = {k for k, v in N.items() if isinstance(v, (int, np.integer)) and not isinstance(v, bool)}
    lines = ["% GENERATED by tools/v2_tables.py -- do not edit. Read with \\val{key}, \\val{key@1}, \\val{key@0}."]
    for k in sorted(N):
        v = N[k]
        if isinstance(v, str):
            for suf in ("", "@1", "@0"):
                lines.append(f"\\expandafter\\def\\csname n@{k}{suf}\\endcsname{{{v}}}")
            continue
        if k in ints:
            txt = f"{int(v):,}".replace(",", "{,}")
            vs = {"": txt, "@1": txt, "@0": txt}
        else:
            vs = {"": f"{v:.2f}", "@1": f"{v:.1f}", "@0": f"{v:.0f}"}
        for suf, t in vs.items():
            t = t[1:] if re.fullmatch(r"-0(\.0+)?", t) else t
            t = t.replace("-", "$-$") if t.startswith("-") else t
            lines.append(f"\\expandafter\\def\\csname n@{k}{suf}\\endcsname{{{t}}}")
    open(os.path.join(GEN, "numbers_v2.tex"), "w").write("\n".join(lines) + "\n")
    print(f"numbers_v2.tex: {len(N)} keys")


