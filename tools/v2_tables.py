"""Generate every number and table added in revision round v2 from results/ (never typed by hand).

Reads (each part is skipped with a message if its input is missing; the manuscript then prints a red
TODO for the missing macros, which the build check catches):
  results/E4/secondary_ci.json        E4, T2   (tools/v2_secondary_ci.py)
  results/T4/recipe_mechanism.json    T4       (tools/v2_recipe_mechanism.py)
  results/E1E2/extended_ci.json       E1, E2   (tools/v2_extended_ci.py)
  results/E1E2/scores/*.json          replicate consistency of retrained checkpoints
  results/E3/e3_ci.json               E3       (tools/v2_e3_ci.py)
  results/E5/...                      E5       (scripts/run_e5.py)
Writes outputs/generated/numbers_v2.tex (read with \\val{key}, \\val{key@1}, \\val{key@0} like
numbers.tex), the supplementary tables supp_v2_*.tex, and frontier_e5.csv for the figure.
Usage: python3 tools/v2_tables.py
"""
import csv
import glob
import json
import os
import re
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import prl_tables as T  # noqa: E402

GEN = os.path.join(ROOT, "outputs", "generated")
R = lambda *p: os.path.join(ROOT, "results", *p)
HDR = "% GENERATED by tools/v2_tables.py -- do not edit\n"
N = {}          # key -> float or int
NEG = lambda s: T.neg(re.sub(r"(?<![\w.])-(0\.0+)(?!\d)", r"\1", s))  # no negative zero


def put(key, v):
    assert key not in N, f"duplicate macro {key}"
    N[key] = v


def ci_txt(c, d=2):
    return NEG(f"[{c[0]:.{d}f}, {c[1]:.{d}f}]")


def bold_if_excludes_zero(pt, cis, d=2):
    txt = NEG(f"{pt:.{d}f}")
    ok = all(c[0] > 0 or c[1] < 0 for c in cis) and len({c[0] > 0 for c in cis}) == 1
    return f"\\textbf{{{txt}}}" if ok else txt


def write(name, lines):
    open(os.path.join(GEN, name), "w").write(HDR + "\n".join(lines) + "\n")


