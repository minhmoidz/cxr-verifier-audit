def attack_table(d):
    """Learned field and field-minus-control rows under the SR and SS attacks (extended set)."""
    C, X = d["contrasts"], d["configs"]
    fmt = lambda e: NEG(f"{e['point']:.2f}")
    def cell(e):
        lo, hi = e["patient+seed"]
        txt = NEG(f"{e['point']:.2f} [{lo:.2f}, {hi:.2f}]")
        return f"\\textbf{{{txt}}}" if (lo > 0 or hi < 0) else txt
    L = [r"\begin{tabular}{llcccc}", r"\toprule",
         r" & & \multicolumn{2}{c}{SR attack (raw reference)} & \multicolumn{2}{c}{SS attack (sanitized reference)} \\",
         r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
         r"Verifier & Quantity & TPR@1\% & AUC & TPR@1\% & AUC \\", r"\midrule"]
    n = 0
    for fam, lab, ctrls in ATTACK_ROWS:
        ff = f"{fam}/ff_mu0.01"
        if ff not in X or any(f"ext/SR/{fam}/ff_mu0.01_minus_{c}" not in C for c in ctrls):
            continue
        if n:
            L.append(r"\addlinespace")
        L.append(f"{lab} & Field $\\mu{{=}}0.01$ & " + " & ".join(fmt(X[ff][f"ext/{pr}/{m}"]) for pr in ("SR", "SS") for m in ("tpr1", "auc")) + r" \\")
        for c in ctrls:
            L.append(f" & Field $-$ {SANLAB[c].lower() if c.startswith('blur') else SANLAB[c].replace('Elastic', 'elastic')} & "
                     + " & ".join(cell(C[f"ext/{pr}/{fam}/ff_mu0.01_minus_{c}"][m]) for pr in ("SR", "SS") for m in ("tpr1", "auc")) + r" \\")
        n += 1
    L += [r"\bottomrule", r"\end{tabular}"]
    return L, n


